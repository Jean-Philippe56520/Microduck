"""PER-P12: create an opt-in, read-only-derived Yocto layer from a verified P11 artifact.

This is a source/recipe candidate, not a BitBake build, installed image or signed release.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tarfile
import tempfile
import tomllib

from scripts.per_p11_v1_source_release import (
    ARCHIVE_NAME, PIN as OEM_SHA, RL_PIN, SOURCE_STATUS,
    ReleaseRefused, verify_archive,
)

YOCTO_SHA = "1ee58387810cebb67ae0d634c351d95024483bce"
BLOBS = {
    "meta-microduck/recipes-microduck/microduck-daemon/microduck-daemon.bb":
        "f6aa890d3e6f417020cad3a31c8dbd9a31619e58",
    "meta-microduck/recipes-microduck/microduck-daemon/microduck-daemon-crates.inc":
        "bbbc22653ac64c42f299f9cab59b50730f507aa7",
    "meta-microduck/conf/layer.conf":
        "1773519b4d564f7a2fe849d978ab0c1fa8354481",
    "kas/microduck.yml":
        "2c638f0b6346a6b318634d61553399238c5c1460",
}
DAEMON_URI = "git://git@github.com/pollen-robotics/microduck_daemon.git;protocol=ssh;branch=main;name=daemon"
BMI_URI = "git://github.com/pollen-robotics/bmi088-rs;protocol=https;nobranch=1;name=bmi088;destsuffix=bmi088-rs"
BMI_SHA = "bd113f317b14923f50f9a12a06678fe162b7fe06"
OEM_FILES = ("60-robot-i2c.rules", "robotctl.bash_completion", "microduck-voice-bank.service")
SCHEMA = "kwipi-p12-yocto-source-layer-v1"
MODEL_NAME = "kwipi-v1-oem-source.tar.gz"


def git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], check=True,
                          capture_output=True, text=True).stdout.strip()


def check_yocto(yocto: Path) -> str:
    if git(yocto, "rev-parse", "HEAD") != YOCTO_SHA:
        raise ReleaseRefused("Yocto SHA differs from pinned source")
    if git(yocto, "status", "--porcelain", "--untracked-files=no"):
        raise ReleaseRefused("Yocto tracked files changed")
    for rel, sha in BLOBS.items():
        f = yocto / rel
        if not f.is_file() or f.is_symlink() or git(yocto, "hash-object", "--", rel) != sha:
            raise ReleaseRefused(f"Yocto audited blob changed: {rel}")
    recipe = (yocto / next(iter(BLOBS))).read_text(encoding="utf-8")
    anchors = (
        DAEMON_URI, BMI_URI, 'SRCREV_bmi088 = "' + BMI_SHA + '"',
        'SRCREV_FORMAT = "daemon_bmi088"',
        'require microduck-daemon-crates.inc',
        'PV = "${MICRODUCK_DAEMON_VERSION}"',
        'inherit cargo cargo-update-recipe-crates pkgconfig systemd useradd',
        'RRECOMMENDS:${PN}:append:aarch64 = " onnxruntime"',
    )
    for a in anchors:
        if recipe.count(a) != 1:
            raise ReleaseRefused(f"Yocto recipe missing/duplicating {a}")
    for file in OEM_FILES:
        if recipe.count("file://" + file) != 1:
            raise ReleaseRefused("OEM resource missing/duplicated")
    inc = (yocto / "meta-microduck/recipes-microduck/microduck-daemon/"
                   "microduck-daemon-crates.inc").read_text(encoding="utf-8")
    if not inc.startswith("# Autogenerated with 'bitbake -c update_crates microduck-daemon'"):
        raise ReleaseRefused("OEM crates include unknown")
    return inc


def read_member(tar: tarfile.TarFile, name: str) -> bytes:
    f = tar.extractfile(name)
    if f is None:
        raise ReleaseRefused(f"archive missing member {name}")
    return f.read()


def checked_artifact(directory: Path) -> tuple[Path, dict, bytes, str]:
    archive = directory / ARCHIVE_NAME
    sidecar = directory / "manifest.json"
    sha_file = directory / (ARCHIVE_NAME + ".sha256")
    if any(not x.is_file() or x.is_symlink() for x in (archive, sidecar, sha_file)):
        raise ReleaseRefused("P11 source/manifest/sha file missing or symlink")
    sha = hashlib.sha256(archive.read_bytes()).hexdigest()
    if sha_file.read_text(encoding="ascii").strip() != f"{sha}  {ARCHIVE_NAME}":
        raise ReleaseRefused("P11 SHA-256 sidecar mismatch")
    m = verify_archive(archive)
    o = json.loads(sidecar.read_text(encoding="utf-8"))
    if (o.get("archive_sha256") != sha or o.get("source_manifest") != m
            or o.get("archive_name") != ARCHIVE_NAME
            or m.get("status") != SOURCE_STATUS or m.get("oem_sha") != OEM_SHA
            or m.get("mujoco_sha") != RL_PIN or m.get("kwipi_seg_weights_included") is not False
            or m.get("detector_enabled_by_default") is not False
            or not re.fullmatch("[0-9a-f]{40}", m.get("companion_sha", ""))):
        raise ReleaseRefused("P11 provenance/weights/defaults mismatch")
    with tarfile.open(archive, "r:gz") as t:
        lock = read_member(t, "Cargo.lock")
        root = read_member(t, "Cargo.toml").decode("utf-8")
        detect_cargo = read_member(t, "duck-detect/Cargo.toml").decode("utf-8")
    if ('version = "0.17.8"' not in root or
            'kwipi-seg-mask-core = { path = "../kwipi-seg-mask-core" }' not in detect_cargo):
        raise ReleaseRefused("unknown P11 OEM Cargo workspace")
    return archive, m, lock, sha


def crates(lock: bytes) -> list[tuple[str, str, str]]:
    packages = tomllib.loads(lock.decode("utf-8"))["package"]
    rows = []
    seen = set()
    bmi = 0
    kwipi = 0
    for p in packages:
        source, name, version = p.get("source", ""), p["name"], p["version"]
        if name == "kwipi-seg-mask-core":
            kwipi += 1
        if source.startswith("registry+"):
            if source != "registry+https://github.com/rust-lang/crates.io-index":
                raise ReleaseRefused("unknown Cargo registry")
            digest = p.get("checksum", "")
            if (not re.fullmatch("[A-Za-z0-9_-]+", name)
                    or not re.fullmatch("[0-9A-Za-z+._-]+", version)
                    or not re.fullmatch("[0-9a-f]{64}", digest)
                    or (name, version) in seen):
                raise ReleaseRefused("invalid/duplicate crates.io dependency")
            seen.add((name, version))
            rows.append((name, version, digest))
        elif source:
            if (not source.startswith("git+https://github.com/pollen-robotics/bmi088-rs")
                    or not source.endswith("#" + BMI_SHA) or name != "bmi088"):
                raise ReleaseRefused("unreviewed Git dependency")
            bmi += 1
    if bmi != 1 or kwipi != 1 or not rows:
        raise ReleaseRefused("BMI088/core dependency absent or duplicated")
    return sorted(rows)


def render_crates(rows: list[tuple[str, str, str]]) -> str:
    lines = [
        "# Generated from P11 Cargo.lock. Replaces, never adds to, old Yocto crate closure.",
        'SRC_URI += " \\',
        *(f"    crate://crates.io/{n}/{v} \\" for n, v, _ in rows),
        '"', "",
        *(f'SRC_URI[{n}-{v}.sha256sum] = "{sha}"' for n, v, sha in rows),
        "",
    ]
    return "\n".join(lines)


def layer_files(manifest: dict, digest: str, rows: list[tuple[str, str, str]]) -> dict[str, str]:
    revision = manifest["companion_sha"]
    v = "0.17.8+kwipi.p12." + revision[:12]
    conf = (
        'BBPATH .= ":${LAYERDIR}"\n'
        'BBFILES += "${LAYERDIR}/recipes-*/*/*.bbappend"\n'
        'BBFILE_COLLECTIONS += "kwipi"\n'
        'BBFILE_PATTERN_kwipi := "^${LAYERDIR}/"\n'
        'BBFILE_PRIORITY_kwipi = "21"\n'
        'LAYERVERSION_kwipi = "1"\n'
        'LAYERDEPENDS_kwipi = "core microduck"\n'
        'LAYERSERIES_COMPAT_kwipi = "wrynose"\n'
    )
    # A bbappend is parsed after the original 'require microduck-daemon-crates.inc'.
    # Replace SRC_URI ENTIRELY to avoid old crates and duplicate daemon fetches.
    app = (
        "# Candidate ONLY, do not ship/flash. No signed updater manifest exists.\n"
        'FILESEXTRAPATHS:prepend := "${THISDIR}/files:"\n'
        f'MICRODUCK_DAEMON_VERSION = "{v}"\n'
        f'MICRODUCK_DAEMON_SRCREV = "{revision}"\n'
        'PV = "${MICRODUCK_DAEMON_VERSION}"\n'
        'SRC_URI = " \\\n'
        f'    file://{MODEL_NAME};subdir=${{BP}};name=kwipisrc \\\n'
        f'    {BMI_URI} \\\n'
        + "".join(f"    file://{f} \\\n" for f in OEM_FILES)
        + '"\n'
        f'SRC_URI[kwipisrc.sha256sum] = "{digest}"\n'
        'SRCREV_FORMAT = "bmi088"\n'
        'require recipes-microduck/microduck-daemon/microduck-daemon-crates-kwipi.inc\n'
    )
    return {
        "conf/layer.conf": conf,
        "recipes-microduck/microduck-daemon/microduck-daemon.bbappend": app,
        "recipes-microduck/microduck-daemon/microduck-daemon-crates-kwipi.inc":
            render_crates(rows),
    }


def verify(layer: Path) -> dict:
    path = layer / "kwipi-layer-provenance.json"
    if not path.is_file() or path.is_symlink():
        raise ReleaseRefused("P12 provenance missing")
    p = json.loads(path.read_text(encoding="utf-8"))
    if (p.get("schema") != SCHEMA or p.get("yocto_sha") != YOCTO_SHA
            or p.get("oem_sha") != OEM_SHA or p.get("source_only") is not True
            or any(p.get(k) is not False for k in (
                "bitbake_parsed", "bitbake_built", "rauc_built",
                "signed_release", "python_companion_installed", "robot_validated"))):
        raise ReleaseRefused("P12 status mismatch")
    archive = layer / "recipes-microduck/microduck-daemon/files" / MODEL_NAME
    if not archive.is_file() or archive.is_symlink():
        raise ReleaseRefused("P12 staged source absent")
    m = verify_archive(archive)
    if (hashlib.sha256(archive.read_bytes()).hexdigest() != p["archive_sha256"]
            or m.get("companion_sha") != p["companion_sha"]):
        raise ReleaseRefused("P12 source SHA/revision changed")
    with tarfile.open(archive, "r:gz") as tar:
        rows = crates(read_member(tar, "Cargo.lock"))
    expected = layer_files(m, p["archive_sha256"], rows)
    for rel, content in expected.items():
        f = layer / rel
        if not f.is_file() or f.is_symlink() or f.read_text(encoding="utf-8") != content:
            raise ReleaseRefused("P12 generated layer changed: " + rel)
    if p.get("crates_generated") != len(rows):
        raise ReleaseRefused("P12 crate count mismatch")
    return p


def stage(yocto: Path, source_dir: Path, output: Path) -> dict:
    if output.exists() or output.is_symlink():
        raise ReleaseRefused("destination already exists")
    upstream_inc = check_yocto(yocto)
    archive, manifest, lock, sha = checked_artifact(source_dir)
    rows = crates(lock)
    upstream = set(re.findall(r"crate://crates\.io/([^/\s]+)/([^\s\\]+)", upstream_inc))
    if not upstream or upstream == {(n, v) for n, v, _ in rows}:
        raise ReleaseRefused("Yocto crates drift assumption changed; re-audit P12")
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="p12-stage-", dir=output.parent) as tmp:
        tmpdir = Path(tmp)
        for rel, source in layer_files(manifest, sha, rows).items():
            f = tmpdir / rel
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(source, encoding="utf-8")
        dest = tmpdir / "recipes-microduck/microduck-daemon/files" / MODEL_NAME
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(archive, dest)
        p = {
            "schema": SCHEMA, "source_only": True,
            "yocto_sha": YOCTO_SHA, "oem_sha": OEM_SHA,
            "companion_sha": manifest["companion_sha"],
            "archive_sha256": sha, "crates_generated": len(rows),
            "original_crates": len(upstream), "crates_regenerated": upstream != {(n, v) for n, v, _ in rows},
            "bitbake_parsed": False, "bitbake_built": False, "rauc_built": False,
            "signed_release": False, "python_companion_installed": False,
            "robot_validated": False, "detector_enabled_by_default": False,
        }
        (tmpdir / "kwipi-layer-provenance.json").write_text(
            json.dumps(p, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        verify(tmpdir)
        tmpdir.rename(output)
    if git(yocto, "status", "--porcelain", "--untracked-files=no"):
        raise ReleaseRefused("read-only Yocto checkout unexpectedly modified")
    return p


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    subs = parser.add_subparsers(dest="command", required=True)
    build = subs.add_parser("stage")
    build.add_argument("--yocto", type=Path, required=True)
    build.add_argument("--source-dir", type=Path, required=True)
    build.add_argument("--output", type=Path, required=True)
    check = subs.add_parser("verify")
    check.add_argument("--layer", type=Path, required=True)
    args = parser.parse_args()
    try:
        print(json.dumps(
            stage(args.yocto, args.source_dir, args.output)
            if args.command == "stage" else verify(args.layer), sort_keys=True))
    except (ReleaseRefused, OSError, KeyError, ValueError, TypeError,
            subprocess.CalledProcessError, tomllib.TOMLDecodeError,
            tarfile.TarError) as exc:
        parser.exit(1, f"PER-P12 STOP: {exc}\n")


if __name__ == "__main__":
    main()
